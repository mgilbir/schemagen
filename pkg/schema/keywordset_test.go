// TestKeywordSetFileIsCurrent recomputes keywordset_gen.go from Schema's json
// tags and fails when the checked-in file differs; SCHEMAGEN_REGENERATE=1
// (go generate ./pkg/schema) writes it instead. See keywordset.go.
func TestKeywordSetFileIsCurrent(t *testing.T) {
	want, err := renderKeywordSet()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("SCHEMAGEN_REGENERATE") == "1" {
		if err := os.WriteFile("keywordset_gen.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile("keywordset_gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		gl, wl := strings.Split(string(got), "\n"), strings.Split(string(want), "\n")
		for i := 0; i < len(gl) && i < len(wl); i++ {
			if gl[i] != wl[i] {
				t.Fatalf("keywordset_gen.go is stale; run go generate ./pkg/schema\nfirst difference at line %d:\n checked in: %s\n recomputed: %s", i+1, gl[i], wl[i])
			}
		}
		t.Fatal("keywordset_gen.go is stale; run go generate ./pkg/schema")
	}
}

// renderKeywordSet writes keywordset_gen.go from marshaledKeywordFields.
func renderKeywordSet() ([]byte, error) {
	t := reflect.TypeOf(Schema{})
	var b bytes.Buffer
	b.WriteString("// Code generated by renderKeywordSet from the json tags of Schema; DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go generate ./pkg/schema\n\n")
	b.WriteString("package schema\n\n")
	b.WriteString("// appendMarshaledKeywords is AppendMarshaledKeywords' reading of s, one\n")
	b.WriteString("// comparison per field in struct order. See keywordset.go.\n")
	b.WriteString("func (s *Schema) appendMarshaledKeywords(dst []string) []string {\n")
	for _, f := range marshaledKeywordFields {
		sf := t.Field(f.index)
		key := fmt.Sprintf("%q", f.key)
		if f.omitZero {
			return nil, fmt.Errorf("field %s is tagged omitzero, which this reading does not model; teach renderKeywordSet the type's IsZero", sf.Name)
		}
		if !f.omitEmpty {
			fmt.Fprintf(&b, "\tdst = append(dst, %s)\n", key)
			continue
		}
		var cond string
		switch sf.Type.Kind() {
		case reflect.String:
			cond = fmt.Sprintf("s.%s != \"\"", sf.Name)
		case reflect.Slice, reflect.Map, reflect.Array:
			cond = fmt.Sprintf("len(s.%s) > 0", sf.Name)
		case reflect.Pointer, reflect.Interface:
			cond = fmt.Sprintf("s.%s != nil", sf.Name)
		case reflect.Bool:
			cond = fmt.Sprintf("s.%s", sf.Name)
		case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64,
			reflect.Float32, reflect.Float64:
			cond = fmt.Sprintf("s.%s != 0", sf.Name)
		default:
			// encoding/json never omits a struct for omitempty.
			fmt.Fprintf(&b, "\tdst = append(dst, %s)\n", key)
			continue
		}
		fmt.Fprintf(&b, "\tif %s {\n\t\tdst = append(dst, %s)\n\t}\n", cond, key)
	}
	b.WriteString("\treturn dst\n}\n")
	return format.Source(b.Bytes())
}

// isEmptyForJSON is encoding/json's isEmptyValue, which is what decides whether
// an omitempty field is written: the rule renderKeywordSet writes out per
// field, and the one the tests here read a field's emptiness by.
func isEmptyForJSON(v reflect.Value) bool {
	switch v.Kind() {
	case reflect.Array, reflect.Map, reflect.Slice, reflect.String:
		return v.Len() == 0
	case reflect.Bool,
		reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
		reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Uintptr,
		reflect.Float32, reflect.Float64,
		reflect.Interface, reflect.Pointer:
		return v.IsZero()
	}
	return false
}
