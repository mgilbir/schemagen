package gocontext

import (
	"bytes"
	"fmt"
	"go/format"
	"hash/crc32"
	"io"
	"io/fs"
	"sort"
	"text/template"
	"text/template/parse"
)

// Entry is one row of the guard table: the action at byte offset Pos of the
// named template, and the guard appended to it.
type Entry struct {
	Template string
	Pos      parse.Pos
	Guard    string
}

// Table is the guard table for an analysis, in template and position order.
func (a *Analysis) Table() []Entry {
	out := make([]Entry, 0, len(a.Sites))
	for _, s := range a.Sites {
		out = append(out, Entry{Template: s.Template, Pos: s.Node.Pos, Guard: s.Context.Guard()})
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Template != out[j].Template {
			return out[i].Template < out[j].Template
		}
		return out[i].Pos < out[j].Pos
	})
	return out
}

// TemplatesHash is a CRC-32C of every *.go.tmpl file in fsys, each written as
// its name, a NUL, its length and its bytes, in name order. It is what ties a
// guard table to the templates it was computed from: the positions in the
// table mean nothing against any other text.
//
// It guards against an accident -- a template edited without regenerating the
// table -- and not against an adversary, who could as well edit the table:
// both are compiled into the same binary. So it is a checksum rather than a
// cryptographic hash, because New pays for it in every process and CRC-32C is
// hardware-accelerated. TestGuardTableIsCurrent is the exact check; it
// recomputes the table and compares it byte for byte.
func TemplatesHash(fsys fs.FS) (string, error) {
	names, err := fs.Glob(fsys, "*.go.tmpl")
	if err != nil {
		return "", err
	}
	if len(names) == 0 {
		return "", fmt.Errorf("gocontext: no templates to hash")
	}
	sort.Strings(names)
	h := crc32.New(crc32.MakeTable(crc32.Castagnoli))
	buf := make([]byte, 64<<10)
	for _, n := range names {
		f, err := fsys.Open(n)
		if err != nil {
			return "", err
		}
		fi, err := f.Stat()
		if err != nil {
			f.Close()
			return "", err
		}
		fmt.Fprintf(h, "%s\x00%d\x00", n, fi.Size())
		_, err = io.CopyBuffer(h, f, buf)
		f.Close()
		if err != nil {
			return "", err
		}
	}
	return fmt.Sprintf("crc32c:%08x", h.Sum32()), nil
}

// RenderTable writes the guard table as the Go source of guards_gen.go in
// package emitter.
func RenderTable(entries []Entry, templatesHash string) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by guardgen from templates/*.go.tmpl; DO NOT EDIT.\n")
	b.WriteString("// Regenerate with: go generate ./pkg/emitter\n\n")
	b.WriteString("package emitter\n\n")
	b.WriteString("// guardTableTemplatesHash is gocontext.TemplatesHash of the templates this\n")
	b.WriteString("// table was computed from. New refuses to start if the embedded templates\n")
	b.WriteString("// hash to anything else.\n")
	fmt.Fprintf(&b, "const guardTableTemplatesHash = %q\n\n", templatesHash)
	b.WriteString("// guardTable is every output action of every template and the guard for the\n")
	b.WriteString("// Go context it writes into. See internal/gocontext.\n")
	b.WriteString("var guardTable = []guardEntry{\n")
	for _, e := range entries {
		fmt.Fprintf(&b, "\t{%q, %d, %q},\n", e.Template, int(e.Pos), e.Guard)
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// GenerateTable parses the templates in fsys with funcs, analyses them and
// renders guards_gen.go. guardgen writes what it returns; the emitter's
// staleness test compares it with the checked-in file.
func GenerateTable(fsys fs.FS, funcs template.FuncMap) ([]byte, error) {
	t, err := template.New("").Funcs(funcs).ParseFS(fsys, "*.go.tmpl")
	if err != nil {
		return nil, fmt.Errorf("gocontext: parsing templates: %w", err)
	}
	an, err := Analyze(t)
	if err != nil {
		return nil, err
	}
	hash, err := TemplatesHash(fsys)
	if err != nil {
		return nil, err
	}
	return RenderTable(an.Table(), hash)
}
